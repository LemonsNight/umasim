/** 技能按鈕／摘要用的繁中名稱；未翻譯回退原始日文。 */
internal fun SkillData.displayNameZhTw(): String = skillNameZhTw[id] ?: name

/**
 * 懸停說明用的繁中訊息。
 * 僅將官方日文說明（info[0]）換成官方繁中說明；其餘（含模擬器條件、
 * 數值、比較符號、百分比、技能 ID、觸發邏輯）一律保留原文。
 */
internal fun SkillData.displayMessagesZhTw(): List<String> {
    val official = skillInfoZhTw[id]
    val firstInfo = info.firstOrNull()
    return messages.map { message ->
        when {
            official != null && firstInfo != null && message == firstInfo -> official
            else -> noticePhraseZhTw[message] ?: message
        }
    }
}

/** 結果圖表／貢獻度表格等只有名稱字串的顯示位置；重名或未翻譯回退日文。 */
internal fun displaySkillNameZhTw(jaName: String): String = uniqueJaNameZhTw[jaName] ?: jaName

/** 顯示模擬器提示用語（notice / invokes.messages）；未收錄者回退日文。 */
internal fun displayNoticeZhTw(text: String): String = noticePhraseZhTw[text] ?: text
