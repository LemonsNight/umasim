$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$files = Get-ChildItem -Path $targetDir -Filter "*.kt" -File

$changed = @()

foreach ($file in $files) {
    $content = [System.IO.File]::ReadAllText($file.FullName)
    $original = $content

    # 長文字列を先に置換して誤置換を減らす
    foreach ($jp in ($translations.Keys | Sort-Object { $_.Length } -Descending)) {
        $content = $content.Replace($jp, $translations[$jp])
    }

    if ($content -ne $original) {
        $backup = $file.FullName + ".zh-Hant.bak"

        if (-not (Test-Path $backup)) {
            [System.IO.File]::WriteAllText($backup, $original, $utf8NoBom)
        }

        [System.IO.File]::WriteAllText($file.FullName, $content, $utf8NoBom)
        $changed += $file.Name
    }
}

